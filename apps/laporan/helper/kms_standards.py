def bbu_series(gender):
    gender = "P" if str(gender).strip().upper().startswith("P") else "L"
    rows = BBU[gender]
    result = {key: [] for key in BBU_COLUMNS}
    result["month"] = []
    for month in range(61):
        result["month"].append(month)
        for key, value in zip(BBU_COLUMNS, rows[month]):
            result[key].append(value)
    return result


def pbu_tbu_series(gender):
    """Bangun kurva PB/U-TB/U bulanan dari referensi WHO daily aktif.

    Sumber runtime sama dengan ground truth deteksi stunting, yaitu file WHO
    expanded Day 0-1856. Untuk grafik KMS 0-60 bulan, tabel harian disampling
    pada usia representatif ``round(month * 30.4375)`` hari. Perhitungan
    ground truth pemeriksaan tetap memakai usia hari eksak, bukan hasil
    sampling grafik ini.
    """
    import csv
    from pathlib import Path

    gender = "P" if str(gender).strip().upper().startswith("P") else "L"
    filename = "lfa_girls_z_exp.csv" if gender == "P" else "lfa_boys_z_exp.csv"
    csv_path = Path(__file__).resolve().parents[2] / "referensi" / "data" / filename

    rows_by_day = {}
    with csv_path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle, delimiter=";")
        for row in reader:
            rows_by_day[int(row["Day"])] = row

    keys = ["sd3neg", "sd2neg", "sd1neg", "median", "sd1", "sd2", "sd3"]
    source_columns = ["SD3neg", "SD2neg", "SD1neg", "SD0", "SD1", "SD2", "SD3"]
    result = {key: [] for key in keys}
    result["month"] = []

    for month in range(61):
        day = int(round(month * 30.4375))
        row = rows_by_day.get(day)
        if row is None:
            continue
        result["month"].append(month)
        for key, column in zip(keys, source_columns):
            value = float(str(row[column]).replace(",", "."))
            result[key].append(round(value, 1))

    return result


